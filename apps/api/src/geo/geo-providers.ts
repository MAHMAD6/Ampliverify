import { Injectable } from '@nestjs/common';
import { setTimeout as sleep } from 'timers/promises';
import { DataForSeoClient, TransientProviderError } from '../keywords/dataforseo.client';

/** Search surfaces observed through DataForSEO (V1 manual §4.1, §5). */
export type Surface = 'google_ai_mode' | 'google_organic';

export const SURFACE_LABEL: Record<Surface, string> = {
  google_ai_mode: 'Google AI Mode',
  google_organic: 'Google AI Overview (organic results)',
};

/**
 * One observed search snapshot. `aiPresent` says whether an AI answer was
 * shown at all for this query/locale; when it is false the brand cannot be
 * "absent from the AI answer", only unobserved.
 */
export type Observation = {
  provider: 'dataforseo';
  surface: Surface;
  providerTaskId: string;
  query: string;
  location: string;
  language: string;
  device: 'desktop' | 'mobile';
  observedAt: string;
  aiPresent: boolean;
  /** AI answer text (AI Mode / AI Overview markdown), never generated by AmpliVerify. */
  text: string;
  /** Sources the AI answer referenced, in order. */
  citations: { url: string; title: string | null; domain: string }[];
  /** Top organic results (organic surface only). */
  organic: { rank: number; url: string; domain: string; title: string | null }[];
  linkedDomains: string[];
  costUsd: number;
  raw: unknown;
};

export class ProviderNotConfiguredError extends Error {}

type Item = Record<string, unknown>;

const PATHS: Record<Surface, string> = { google_ai_mode: '/serp/google/ai_mode', google_organic: '/serp/google/organic' };

const hostOf = (url: string) => {
  try {
    return new URL(url).hostname.toLowerCase().replace(/^www\./, '');
  } catch {
    return '';
  }
};

/** Extracts the AI answer and its references from a DataForSEO advanced SERP result. */
export function normalizeSerp(surface: Surface, result: Item | null) {
  const items = ((result?.items as Item[] | undefined) ?? []).filter(Boolean);
  const ai = items.filter((i) => i.type === 'ai_overview');
  const textOf = (i: Item): string => {
    if (typeof i.markdown === 'string') return i.markdown;
    if (typeof i.text === 'string') return i.text;
    return ((i.items as Item[] | undefined) ?? []).map(textOf).filter(Boolean).join('\n');
  };
  const refs: { url: string; title: string | null; domain: string }[] = [];
  const pushRef = (r: Item) => {
    const url = typeof r.url === 'string' ? r.url : null;
    if (!url || refs.some((x) => x.url === url)) return;
    refs.push({ url, title: typeof r.title === 'string' ? r.title : null, domain: typeof r.domain === 'string' ? r.domain.replace(/^www\./, '') : hostOf(url) });
  };
  for (const a of ai) {
    for (const r of (a.references as Item[] | undefined) ?? []) pushRef(r);
    for (const el of (a.items as Item[] | undefined) ?? []) for (const r of (el.references as Item[] | undefined) ?? []) pushRef(r);
  }
  const organic = surface === 'google_organic' ? items.filter((i) => i.type === 'organic' && typeof i.url === 'string').slice(0, 20).map((i) => ({ rank: Number(i.rank_group ?? i.rank_absolute ?? 0), url: String(i.url), domain: String(i.domain ?? hostOf(String(i.url))).replace(/^www\./, ''), title: typeof i.title === 'string' ? i.title : null })) : [];
  const text = ai.map(textOf).join('\n\n').trim();
  const linkedDomains = [...new Set([...refs.map((r) => r.domain), ...organic.map((o) => o.domain)].filter(Boolean))];
  return { aiPresent: ai.length > 0, text, citations: refs, organic, linkedDomains };
}

/**
 * GEO evidence collection: DataForSEO Google AI Mode and Google Organic
 * (AI Overview) in Standard queued mode. Results are observations from saved
 * provider evidence; AmpliVerify never generates an answer and presents it
 * as an AI platform's result.
 */
@Injectable()
export class GeoProviders {
  constructor(private readonly dataforseo: DataForSeoClient) {}

  isConfigured(provider: string) {
    return provider === 'dataforseo' && this.dataforseo.configured;
  }

  async observe(surface: Surface, query: string, opts: { country?: string | null; language?: string | null; device?: 'desktop' | 'mobile'; pollMs?: number; timeoutMs?: number }): Promise<Observation> {
    if (!this.dataforseo.configured) throw new ProviderNotConfiguredError('DataForSEO is not configured');
    const location = this.dataforseo.locationName(opts.country || 'us');
    const language = opts.language || 'en';
    const device = opts.device ?? 'desktop';
    const op = `geo.${surface}`;
    const task = await this.retry(() => this.dataforseo.postTask(`${PATHS[surface]}/task_post`, { keyword: query.slice(0, 700), location_name: location, language_code: language, device, ...(surface === 'google_organic' ? { depth: 20, load_async_ai_overview: true } : {}) }, op));
    const deadline = Date.now() + (opts.timeoutMs ?? 6 * 60_000);
    let delay = opts.pollMs ?? 10_000;
    for (;;) {
      await sleep(delay);
      const got = await this.retry(() => this.dataforseo.getTask(`${PATHS[surface]}/task_get/advanced/${encodeURIComponent(task.id)}`, op));
      if (got.ready) {
        const n = normalizeSerp(surface, got.result);
        return { provider: 'dataforseo', surface, providerTaskId: task.id, query, location, language, device, observedAt: new Date().toISOString(), ...n, costUsd: task.cost + got.cost, raw: got.result };
      }
      if (Date.now() > deadline) throw new ObservationIncompleteError(`DataForSEO task ${task.id} did not finish in time`);
      delay = Math.min(delay * 1.5, 30_000);
    }
  }

  /** Retries throttling / 5xx / network failures with exponential backoff. */
  private async retry<T>(fn: () => Promise<T>, attempts = 4): Promise<T> {
    for (let i = 0; ; i++) {
      try {
        return await fn();
      } catch (err) {
        if (!(err instanceof TransientProviderError) || i >= attempts - 1) throw err;
        await sleep(1000 * 2 ** i);
      }
    }
  }
}

/** Task timed out: the observation is incomplete, not "not visible". */
export class ObservationIncompleteError extends Error {}

/** Pure analysis of one observation: brand/competitor mentions, ranking, citation of the brand's domain. */
export function analyzeAnswer(
  answer: { text: string; citations: { url: string }[] },
  brand: { names: string[]; domains: string[] },
  competitors: { id: string; name: string; domain: string | null }[],
) {
  const text = answer.text;
  const lower = text.toLowerCase();
  const firstIndex = (terms: string[]) => {
    let best = -1;
    for (const term of terms.map((t) => t.trim().toLowerCase()).filter((t) => t.length >= 2)) {
      const re = new RegExp(`(^|[^\\p{L}\\p{N}])${term.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')}(?=$|[^\\p{L}\\p{N}])`, 'iu');
      const m = re.exec(lower);
      if (m) {
        const idx = m.index + m[1].length;
        if (best < 0 || idx < best) best = idx;
      }
    }
    return best;
  };
  const brandDomains = brand.domains.map((d) => d.toLowerCase().replace(/^www\./, ''));
  const brandIdx = firstIndex([...brand.names, ...brandDomains]);
  const competitorHits = competitors
    .map((c) => ({ ...c, idx: firstIndex([c.name, ...(c.domain ? [c.domain] : [])]) }))
    .filter((c) => c.idx >= 0);

  // Rank = order of first appearance among brand + competitors (1 = first).
  const ordered = [...(brandIdx >= 0 ? [{ key: 'brand', idx: brandIdx }] : []), ...competitorHits.map((c) => ({ key: c.id, idx: c.idx }))].sort((a, b) => a.idx - b.idx);
  const rankOf = (key: string) => {
    const i = ordered.findIndex((o) => o.key === key);
    return i < 0 ? null : i + 1;
  };

  const citationHosts = answer.citations.map((c) => hostOf(c.url));
  const brandCitationRank = citationHosts.findIndex((h) => brandDomains.some((d) => h === d || h.endsWith(`.${d}`)));
  const sentences = text.split(/(?<=[.!?])\s+/).filter((s) => brand.names.some((n) => n && s.toLowerCase().includes(n.toLowerCase())));

  return {
    mentioned: brandIdx >= 0,
    position: rankOf('brand'),
    cited: brandCitationRank >= 0,
    citationRank: brandCitationRank >= 0 ? brandCitationRank + 1 : null,
    mentionCount: brand.names.reduce((n, name) => n + (name ? lower.split(name.toLowerCase()).length - 1 : 0), 0),
    excerpt: sentences[0]?.slice(0, 400) ?? null,
    competitors: competitorHits.map((c) => ({ id: c.id, name: c.name, position: rankOf(c.id) })),
    citationHosts,
  };
}
